"""``inari serve`` without a profile: llama-server's router mode.

One llama-server listens on one port and starts / stops a child llama-server per model on demand
(``"model": "<name>"`` in a request, or POST /models/load). Every inari profile becomes a model preset
named after the profile, written to ``~/.inari/router/presets.ini``; models in the HF cache are listed
by llama-server itself.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import httpx

from inari import server
from inari.config import Config, home
from inari.profiles import Profile, _resolve_refs, list_profiles

NAME = "@router"  # RunInfo name (cannot clash with a profile: profile names start with a letter/digit)
# set by the router for each instance; meaningless in a preset
ROUTER_OWNED = {"host", "port", "alias", "a", "api-key", "hf-repo", "hf", "hfr", "model-url", "mu"}


def router_dir() -> Path:
    p = home() / "router"
    p.mkdir(parents=True, exist_ok=True)
    return p


def preset_path() -> Path:
    return router_dir() / "presets.ini"


def _ini_value(v: Any) -> str | None:
    if v is True:
        return "true"
    if v is False or v is None:
        return None
    if isinstance(v, list):
        vals = [x for x in (_ini_value(x) for x in v) if x is not None]
        return ",".join(vals) if vals else None
    s = str(v)
    return s.replace("\n", " ")


def _extra_pairs(extra: list[str]) -> tuple[list[tuple[str, str]], list[str]]:
    """``["--no-webui", "--temp", "0.7"]`` -> ``[("no-webui", "true"), ("temp", "0.7")]``."""
    out, bad = [], []
    i = 0
    while i < len(extra):
        tok = extra[i]
        if not tok.startswith("-"):
            bad.append(tok)
            i += 1
            continue
        key, eq, val = tok.lstrip("-").partition("=")
        if eq:
            out.append((key, val))
        elif i + 1 < len(extra) and not extra[i + 1].startswith("-"):
            out.append((key, extra[i + 1]))
            i += 1
        else:
            out.append((key, "true"))
        i += 1
    return out, bad


@dataclass
class Presets:
    text: str
    names: list[str] = field(default_factory=list)
    env: dict[str, str] = field(default_factory=dict)  # non-LLAMA_ARG env vars from profiles (router-wide)
    warnings: list[str] = field(default_factory=list)


def build_presets(cfg: Config, load: list[str] | None = None) -> Presets:
    load = load or []
    res = Presets(text="")
    lines = ["; generated by inari from ~/.inari/profiles — edits are overwritten on `inari serve`", "version = 1", ""]
    for n in list_profiles():
        try:
            p = Profile.load(n)
        except Exception as e:
            res.warnings.append(f"{n}: skipped ({e})")
            continue
        mp = p.model_path(cfg)
        if mp is None or not mp.exists():
            res.warnings.append(f"{n}: skipped — model file missing")
            continue
        sec = [f"[{n}]", f"model = {mp}"]
        for key, value in p.args.items():
            k = key.lstrip("-")
            if k in ROUTER_OWNED:
                continue
            v = _ini_value(_resolve_refs(value, cfg))
            if v is not None:
                sec.append(f"{k} = {v}")
        pairs, bad = _extra_pairs(p.extra)
        sec += [f"{k} = {v}" for k, v in pairs if k not in ROUTER_OWNED]
        if bad:
            res.warnings.append(f"{n}: ignored extra args {' '.join(bad)}")
        for k, v in p.env.items():
            if k.startswith("LLAMA_ARG_"):
                sec.append(f"{k} = {v}")
            elif res.env.get(k, v) != v:
                res.warnings.append(f"{n}: env {k}={v} conflicts with another profile — using {res.env[k]}")
            else:
                res.env[k] = v
        if n in load:
            sec.append("load-on-startup = true")
        lines += sec + [""]
        res.names.append(n)
    res.text = "\n".join(lines)
    missing = [x for x in load if x not in res.names]
    if missing:
        res.warnings.append(f"--load: no usable profile named {', '.join(missing)}")
    return res


def build_command(cfg: Config, *, host: str, port: int, models_max: int | None = None) -> list[str]:
    binary = cfg.server_binary()
    if not binary:
        raise FileNotFoundError("llama-server not found. Put it on PATH or run: "
                                "inari config set llama_server <path-to-llama-server>")
    cmd = [binary, "--models-preset", str(preset_path()), "--host", host, "--port", str(port),
           "--metrics", "-lv", "4"]  # inherited by every model instance
    if models_max is not None:
        cmd += ["--models-max", str(models_max)]
    return cmd


def url_for(host: str, port: int) -> str:
    h = "127.0.0.1" if host in ("0.0.0.0", "::", "") else host
    return f"http://{h}:{port}"


def launch(cfg: Config, *, host: str = "127.0.0.1", port: int = 8080, models_max: int | None = None,
           load: list[str] | None = None) -> tuple[server.RunInfo, subprocess.Popen, Presets]:
    pre = build_presets(cfg, load)
    cmd = build_command(cfg, host=host, port=port, models_max=models_max)
    if server.port_in_use(host, port):
        raise RuntimeError(f"port {port} is already in use")
    preset_path().write_text(pre.text, encoding="utf-8")
    run, proc = server.spawn(NAME, cmd, url_for(host, port), cfg, env=pre.env, log_name="router")
    return run, proc, pre


# ───────── HTTP API ─────────
def models(client: httpx.Client, url: str) -> list[dict]:
    r = client.get(url + "/models")
    r.raise_for_status()
    return list(r.json().get("data", []))


def status_of(m: dict) -> str:
    st = m.get("status")
    return str(st.get("value", "")) if isinstance(st, dict) else str(st or "")


def _post(url: str, path: str, model: str) -> str:
    """'' on success, else an error message."""
    try:
        r = httpx.post(url + path, json={"model": model}, timeout=10)
    except httpx.HTTPError as e:
        return str(e)
    if r.status_code == 200:
        return ""
    try:
        return str(r.json().get("error", {}).get("message") or r.text)
    except ValueError:
        return r.text or f"HTTP {r.status_code}"


def load_model(url: str, model: str) -> str:
    return _post(url, "/models/load", model)


def unload_model(url: str, model: str) -> str:
    return _post(url, "/models/unload", model)
